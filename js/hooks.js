/**
 * Ключ хука по значению utm_content или null, если метки нет или она чужая.
 * Метка режется на слова по любым символам кроме латиницы и цифр: «hook_math_b_v1» → hook, math, b, v1.
 * Совпадение — целое слово, поэтому «knowhow» и «homepage» хук не включают.
 * Та же логика продублирована в скрипте <head> (scripts/build.py, HEAD_HOOK_SCRIPT) — тест tests/hooks.test.mjs сверяет их.
 * @param {string | null | undefined} utmContent
 * @returns {string | null}
 */
export function pickHook(utmContent) {
  const words = String(utmContent ?? '').toLowerCase().split(/[^a-z0-9]+/).filter(Boolean);
  const math = words.indexOf('math');
  if (math !== -1) return words[math + 1] === 'a' ? 'math_a' : 'math_b';
  return ['compare', 'clients', 'zero', 'home', 'now'].find((key) => words.includes(key)) ?? null;
}
